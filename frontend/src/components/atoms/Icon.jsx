const ICON_SIZES = {
  sm: 12,
  md: 14,
  lg: 16,
  xl: 18,
}

/**
 * Renders a named SVG icon from the design system set.
 * @param {{ name: string, size?: number, strokeWidth?: number, color?: string }} props
 */
export default function Icon({ name, size = 16, strokeWidth = 1.5, color = 'currentColor' }) {
  const paths = ICON_PATHS[name]

  if (paths) {
    return (
      <IconSvg size={size} strokeWidth={strokeWidth} color={color}>
        {paths}
      </IconSvg>
    )
  }

  return (
    <span style={{ display: 'inline-flex' }}>
      <span
        style={{
          display: 'inline-flex',
          alignItems: 'center',
          justifyContent: 'center',
          width: size,
          height: size,
          borderRadius: 'var(--radius-sm)',
          border: '1px solid var(--border)',
          background: 'var(--bg-tertiary)',
        }}
      >
        <IconSvg size={Math.max(size - 6, 8)} strokeWidth={strokeWidth} color={color}>
          <circle cx="12" cy="12" r="4" />
        </IconSvg>
      </span>
    </span>
  )
}

export { ICON_SIZES }
